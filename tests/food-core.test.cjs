const assert = require('node:assert/strict');
require('../assets/js/food-core.js');
require('../assets/js/food-data.js');
const C = globalThis.FITCALC_FOOD_CORE;
const foods = globalThis.FITCALC_FOODS;
const banana = foods[0];
const sample = { ...banana, carbs: 20 };
assert.equal(C.calculate(sample, 150).kcal, 133.5);
assert.equal(Math.round(C.calculate(sample, 150).kcal), 134);
assert.equal(C.calculate(sample, 150).carbs, 30);
assert.equal(C.calculate(sample, 300).kcal, 267);
for (const amount of [NaN, Infinity, 0, -1, 5000.1, .01, 100.11]) assert.throws(() => C.calculate(sample, amount));
for (const amount of [.1, 1, 150.1, 1000, 1200, 5000]) assert.ok(C.validAmount(amount));
assert.throws(() => C.calculate({ ...sample, baseGrams: 0 }, 100));
assert.throws(() => C.calculate({ ...sample, kcal: -10 }, 100));
assert.throws(() => C.calculate({ ...sample, fat: Infinity }, 100));
assert.throws(() => C.calculate({ ...sample, fat: 1e308 }, 5000));
assert.ok(Number.isNaN(C.number('')));
assert.equal(C.search(foods, '바 나 나', '전체').length, 1);
assert.equal(C.search(foods, '밥', '밥 / 곡류').length, 2);
assert.equal(C.search(foods, '바나나', '육류').length, 0);
assert.equal(C.search(foods, '등록되지않은음식', '전체').length, 0);
const items = [400, 650, 700, 250].map((kcal, index) => ({ food: { ...sample, kcal }, grams: 100, meal: C.meals[index] }));
const totals = C.totals(items);
assert.equal(totals.kcal, 2000);
assert.deepEqual(Object.values(totals.meals), [400, 650, 700, 250]);
assert.ok(Math.abs(C.macroShares(totals).reduce((a,b) => a+b, 0) - 100) < 1e-10);
assert.equal(C.displayShares([100/3,100/3,100/3]).reduce((a,b) => Math.round((a+b)*10)/10, 0), 100);
assert.deepEqual(C.macroShares({ carbs: 0, protein: 0, fat: 0 }), [0,0,0]);
assert.equal(1500 / 2000 * 100, 75);
const missing = { ...sample, carbs: null, protein: null, fat: null };
assert.equal(C.calculate(missing, 150).carbs, null);
assert.equal(C.totals([{ food: missing, grams: 150, meal: '점심' }]).missing.carbs, 1);
assert.equal(C.totals([{ food: missing, grams: 150, meal: '점심' }]).kcal, 133.5);
assert.equal(C.validDate('2024-02-29'), true);
for (const date of ['', '2025-02-29', '2026-13-01', '2026-10-40', '2026-1-1', '__proto__']) assert.equal(C.validDate(date), false);
assert.equal(C.localDate(new Date(2026,9,8,0,1)), '2026-10-08');
const stored = new Map();
globalThis.localStorage = { getItem: key => stored.get(key) ?? null, setItem: (key,value) => stored.set(key,value), removeItem: key => stored.delete(key) };
require('../assets/js/food-storage.js');
const S = globalThis.FITCALC_FOOD_STORAGE;
const record = { version: 1, goal: 2000, items: [{ id: 'item1', food: sample, grams: 150, meal: '점심', createdAt: new Date().toISOString() }] };
assert.ok(S.save('2026-10-08', record).ok);
assert.equal(S.load('2026-10-08').record.items.length, 1);
assert.equal(S.load('2026-10-07').record.items.length, 0);
S.save('2026-10-07', record);
assert.ok(S.clear('2026-10-08').ok);
assert.equal(S.load('2026-10-07').record.items.length, 1);
stored.set('fitcalc-food-log-v1:2026-10-06', '{broken');
assert.ok(S.load('2026-10-06').warning);
assert.equal(S.save('2026-10-06', record).ok, false);
assert.equal(stored.get('fitcalc-food-log-v1:2026-10-06'), '{broken');
assert.equal(S.validate({ ...record, items: [...record.items, ...record.items] }), false);
assert.equal(S.validate({ ...record, goal: 0 }), false);
assert.equal(S.validate({ ...record, items: [{ ...record.items[0], grams: -1 }] }), false);
globalThis.localStorage.setItem = () => { throw new Error('quota'); };
assert.equal(S.save('2026-10-09', record).ok, false);
console.log('PASS: arithmetic, validation, search, macros, local dates, date isolation, corruption protection and quota errors.');
